"""评论分类的公共常量。

五类分类（bug / suggestion / complaint / praise / other）的合法集合与中文定义集中在此，
供 classifier.py（Steam/小黑盒/Discord）与 qq_analyzer.py（QQ）共用，
保证全平台分类口径一致，改一处即全平台生效。
"""

# 合法类别集合（前端 BugFeed/CommentTable 依赖这些字符串，不可随意增删）
CATEGORIES: set[str] = {"bug", "suggestion", "complaint", "praise", "other"}

# 五类的详细中文定义与例子。重点收紧 bug 边界，减少误报：
# 只有「程序行为与设计预期不符的技术性缺陷」才算 bug，单纯的玩家不满归 complaint。
CATEGORY_GUIDE_ZH = """\
分类标准（从下面 5 个里选一个最符合的）：
  bug        — 游戏实际运行与设计预期不符的【技术性缺陷】，即「程序行为出错了」。
               例：闪退/崩溃、报错弹窗、技能/功能失效、数据存档丢失、显示或数值异常、
                   卡死无法继续、进不了游戏、按钮点击无反应。
               例：“bug”、“不对”、“卡死”、“卡住”、“为什么”、“怎么”
               判定要点：必须能指向某个具体的、非预期的错误现象。
  suggestion — 玩家希望新增或修改某个功能/设计/数值。
               例："建议加个XXX"、"能不能把XXX改成YYY"、"希望增加..."、"这英雄太弱建议加强"。
  complaint  — 对游戏【有意设计】的不满（不是程序出错，是玩家不满意）。
               例：难度太高/平衡性差/某英雄太弱、价格太贵、付费设计、更新太慢、某机制不合理。
  praise     — 明确的正面评价。
               例："这个版本改得很好"、"XXX功能做得很棒"。
  other      — 与游戏相关但不属于以上，包括求助/提问。
               例：攻略讨论、资讯转发、活动；以及"怎么解锁第二章""为什么我打不过"等提问。

⚠️ bug 与 complaint 的关键区分（减少误报）：
  - 描述的是「程序行为出错」（崩溃、报错、功能失效、数据异常）→ bug
  - 只是「玩家不满意」（嫌难、嫌贵、嫌弱、单纯骂街且无具体缺陷现象）→ complaint
  - 求助/提问（"怎么…""为什么我打不过…"）→ other，不要判成 bug
  例："太难了打不过" / "这英雄太弱" / "价格太贵" / "这游戏真垃圾"（无具体故障）→ 都不是 bug。\
"""
